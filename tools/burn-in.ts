import { spawnSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { summariseRuns, type Report } from '../src/reporting/flakiness';

/**
 * Runs the whole suite several times against the self-hosted app and reports
 * any test that does not give the same result every time.
 * Usage: npm run burn-in            (5 repeats)
 *        npm run burn-in -- 10      (10 repeats)
 * Results come from real runs only.
 */

const TARGET_URL = 'http://localhost:3000';
const REPORT_DIR = resolve('reports');
const REPORT_FILE = resolve(REPORT_DIR, 'burn-in.json');

function readRepeats(): number {
  const value = Number(process.argv[2] ?? '5');
  if (!Number.isInteger(value) || value < 2 || value > 50) {
    console.error('Repeat count must be a whole number from 2 to 50.');
    process.exit(2);
  }
  return value;
}

function main(): void {
  const repeats = readRepeats();
  mkdirSync(REPORT_DIR, { recursive: true });
  console.log(`Running the suite ${String(repeats)} times against ${TARGET_URL}...`);

  const result = spawnSync(
    `npx playwright test --repeat-each=${String(repeats)} --reporter=json --grep-invert @quarantine`,
    {
      shell: true,
      encoding: 'utf8',
      maxBuffer: 50 * 1024 * 1024,
      env: {
        ...process.env,
        UI_BASE_URL: TARGET_URL,
        PLAYWRIGHT_JSON_OUTPUT_NAME: REPORT_FILE,
      },
    },
  );

  let report: Report;
  try {
    report = JSON.parse(readFileSync(REPORT_FILE, 'utf8')) as Report;
  } catch {
    throw new Error(`No readable report (exit ${String(result.status)}).\n${result.stderr}`);
  }

  const summaries = summariseRuns(report);
  const unstable = summaries.filter((s) => s.verdict !== 'stable');
  const defect = process.env.DEFECT ? `\`${process.env.DEFECT}\`` : 'none';
  const date = new Date().toISOString().slice(0, 10);

  const lines = [
    '# Burn-in results',
    '',
    `Generated by \`npm run burn-in\` on ${date} against the self-hosted target app.`,
    `Repeats per test: ${String(repeats)}. Defect injected: ${defect}.`,
    `Tests judged: ${String(summaries.length)}. Stable: ${String(summaries.length - unstable.length)}. ` +
      `Not stable: ${String(unstable.length)}.`,
    '',
  ];
  if (unstable.length > 0) {
    lines.push('| Test | Runs | Passed | Failed | Verdict |', '| --- | --- | --- | --- | --- |');
    for (const s of unstable) {
      lines.push(
        `| ${s.name} | ${String(s.runs)} | ${String(s.passed)} | ${String(s.failed)} | **${s.verdict}** |`,
      );
    }
    lines.push('');
  }

  writeFileSync(resolve('docs', 'burn-in-results.md'), lines.join('\n'));
  console.log(lines.join('\n'));
  if (unstable.length > 0) process.exit(1);
}

main();
