import { spawnSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

/**
 * Runs the UI suite once per injected defect against the self-hosted target app
 * and records which defects the suite caught. Results come from real runs only.
 */

interface Defect {
  id: string;
  description: string;
}

const DEFECTS: Defect[] = [
  { id: 'locked-user-can-login', description: 'Locked-out user is allowed to log in' },
  { id: 'skip-auth-inventory', description: 'Inventory page opens without logging in' },
  { id: 'wrong-cart-count', description: 'Cart badge shows one item too many' },
  { id: 'sort-za-broken', description: 'Sorting Z to A does not reverse the order' },
  { id: 'checkout-no-validation', description: 'Checkout accepts an empty first name' },
  { id: 'logout-keeps-session', description: 'Logout does not end the session' },
  { id: 'wrong-confirmation-text', description: 'Order confirmation text is wrong' },
  { id: 'no-lastname-validation', description: 'Checkout accepts an empty last name' },
];

interface Spec {
  title: string;
  ok: boolean;
}

interface Suite {
  title: string;
  specs?: Spec[];
  suites?: Suite[];
}

interface Report {
  suites: Suite[];
}

const TARGET_URL = 'http://localhost:3000';
const REPORT_DIR = resolve('reports');

function collectFailed(suites: Suite[], parents: string[] = []): string[] {
  const failed: string[] = [];
  for (const suite of suites) {
    const path = [...parents, suite.title];
    for (const spec of suite.specs ?? []) {
      if (!spec.ok) failed.push([...path, spec.title].join(' > '));
    }
    failed.push(...collectFailed(suite.suites ?? [], path));
  }
  return failed;
}

function runSuite(defectId: string): string[] {
  const reportFile = resolve(REPORT_DIR, `defect-${defectId || 'baseline'}.json`);
  const result = spawnSync('npx playwright test --reporter=json', {
    shell: true,
    encoding: 'utf8',
    env: {
      ...process.env,
      UI_BASE_URL: TARGET_URL,
      DEFECT: defectId,
      PLAYWRIGHT_JSON_OUTPUT_NAME: reportFile,
    },
  });
  try {
    const report = JSON.parse(readFileSync(reportFile, 'utf8')) as Report;
    return collectFailed(report.suites);
  } catch {
    throw new Error(
      `No readable report for "${defectId || 'baseline'}" (exit ${String(result.status)}).\n` +
        `${result.stderr}`,
    );
  }
}

function main(): void {
  mkdirSync(REPORT_DIR, { recursive: true });

  console.log('Running baseline (no defect)...');
  const baselineFailures = runSuite('');
  if (baselineFailures.length > 0) {
    console.error('Baseline is not clean, so defect results would be meaningless:');
    for (const title of baselineFailures) console.error(`  - ${title}`);
    process.exit(1);
  }

  const rows: string[] = [];
  let missed = 0;
  for (const defect of DEFECTS) {
    console.log(`Injecting ${defect.id}...`);
    const failed = runSuite(defect.id);
    const caught = failed.length > 0;
    if (!caught) missed += 1;
    rows.push(
      `| \`${defect.id}\` | ${defect.description} | ${caught ? 'caught' : '**MISSED**'} | ` +
        `${caught ? failed.join('<br>') : '-'} |`,
    );
  }

  const date = new Date().toISOString().slice(0, 10);
  const markdown = [
    '# Defect-injection results',
    '',
    `Generated by \`npm run defects\` on ${date} against the self-hosted target app.`,
    `Caught: ${String(DEFECTS.length - missed)} of ${String(DEFECTS.length)}.`,
    '',
    '| Defect | What is broken | Result | Failing tests |',
    '| --- | --- | --- | --- |',
    ...rows,
    '',
    'A defect counts as caught when at least one test fails with it injected and none fail without it.',
    '',
  ].join('\n');

  writeFileSync(resolve('docs', 'defect-injection-results.md'), markdown);
  console.log(markdown);
}

main();
