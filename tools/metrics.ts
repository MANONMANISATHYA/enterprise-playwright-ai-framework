import { appendFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { FAILURE_CATEGORIES } from '../src/reporting/failures';
import { summariseRuns, type Report as BurnInReport } from '../src/reporting/flakiness';
import { summariseEvaluation, type EvaluationReport } from '../src/ai/evaluation';
import { computeMetrics, type Report, type RunMetrics } from '../src/reporting/metrics';

/**
 * Reads the last Playwright JSON report (reports/results.json, written by every `npm test`),
 * prints run metrics, appends one line to reports/metrics-history.jsonl and writes docs/metrics-latest.md.
 * Usage: npm run metrics            (default report)
 *        npm run metrics -- path\to\report.json
 */

const REPORT_DIR = resolve('reports');
const HISTORY_FILE = resolve(REPORT_DIR, 'metrics-history.jsonl');
const BURN_IN_FILE = resolve(REPORT_DIR, 'burn-in.json');
const AI_EVALUATION_FILE = resolve(REPORT_DIR, 'ai-evaluation.json');
const TREND_LENGTH = 10;

type HistoryEntry = Pick<
  RunMetrics,
  'startTime' | 'total' | 'passed' | 'failed' | 'flaky' | 'skipped' | 'durationMs'
>;

const seconds = (ms: number): string => `${(ms / 1000).toFixed(1)}s`;
const percent = (part: number, whole: number): string =>
  whole === 0 ? 'n/a' : `${((part / whole) * 100).toFixed(1)}%`;

function readHistory(): HistoryEntry[] {
  if (!existsSync(HISTORY_FILE)) return [];
  return readFileSync(HISTORY_FILE, 'utf8')
    .split('\n')
    .filter((line) => line.trim() !== '')
    .map((line) => JSON.parse(line) as HistoryEntry);
}

function burnInSummary(): string {
  if (!existsSync(BURN_IN_FILE)) return 'No burn-in report found. Run `npm run burn-in` first.';
  const report = JSON.parse(readFileSync(BURN_IN_FILE, 'utf8')) as BurnInReport;
  const summaries = summariseRuns(report);
  const unstable = summaries.filter((s) => s.verdict !== 'stable');
  return `${String(summaries.length)} tests judged, ${String(unstable.length)} not stable (from the last burn-in).`;
}

function aiEvaluationSummary(): string {
  if (!existsSync(AI_EVALUATION_FILE)) return 'not measured yet. Run `npm run ai:eval`.';
  return summariseEvaluation(
    JSON.parse(readFileSync(AI_EVALUATION_FILE, 'utf8')) as EvaluationReport,
  );
}

function main(): void {
  const input = resolve(process.argv[2] ?? resolve(REPORT_DIR, 'results.json'));
  if (!existsSync(input)) {
    console.error(`No report at ${input}. Run \`npm test\` first.`);
    process.exit(2);
  }
  const metrics = computeMetrics(JSON.parse(readFileSync(input, 'utf8')) as Report);

  mkdirSync(REPORT_DIR, { recursive: true });
  const history = readHistory();
  const entry: HistoryEntry = {
    startTime: metrics.startTime,
    total: metrics.total,
    passed: metrics.passed,
    failed: metrics.failed,
    flaky: metrics.flaky,
    skipped: metrics.skipped,
    durationMs: metrics.durationMs,
  };
  if (!history.some((h) => h.startTime === entry.startTime)) {
    appendFileSync(HISTORY_FILE, `${JSON.stringify(entry)}\n`);
    history.push(entry);
  }

  const date = new Date().toISOString().slice(0, 10);
  const lines = [
    '# Run metrics',
    '',
    `Generated by \`npm run metrics\` on ${date} from the last Playwright JSON report.`,
    '',
    `- Tests: ${String(metrics.total)} (passed ${String(metrics.passed)}, failed ${String(metrics.failed)}, ` +
      `flaky ${String(metrics.flaky)}, skipped ${String(metrics.skipped)})`,
    `- Pass rate: ${percent(metrics.passed, metrics.total - metrics.skipped)}`,
    `- Run duration: ${seconds(metrics.durationMs)}`,
    `- Burn-in: ${burnInSummary()}`,
    `- AI evaluation quality: ${aiEvaluationSummary()}`,
    '',
    '## Slowest tests',
    '',
    '| Test | Duration |',
    '| --- | --- |',
    ...metrics.slowest.map((s) => `| ${s.name} | ${seconds(s.durationMs)} |`),
    '',
    '## Failure categories',
    '',
    '| Category | Count |',
    '| --- | --- |',
    ...FAILURE_CATEGORIES.map((c) => `| ${c} | ${String(metrics.failureCategories[c])} |`),
    '',
  ];
  if (metrics.failures.length > 0) {
    lines.push(
      '## Failures',
      '',
      '| Test | Category | First line of the error |',
      '| --- | --- | --- |',
    );
    for (const f of metrics.failures) {
      lines.push(`| ${f.name} | ${f.category} | ${f.message.replaceAll('|', '\\|')} |`);
    }
    lines.push('');
  }
  lines.push(
    '## Trend (most recent runs)',
    '',
    '| Started | Passed | Failed | Flaky | Duration |',
    '| --- | --- | --- | --- | --- |',
  );
  for (const h of history.slice(-TREND_LENGTH)) {
    lines.push(
      `| ${h.startTime} | ${String(h.passed)}/${String(h.total)} | ${String(h.failed)} | ${String(h.flaky)} | ${seconds(h.durationMs)} |`,
    );
  }
  lines.push('');

  writeFileSync(resolve('docs', 'metrics-latest.md'), lines.join('\n'));
  console.log(lines.join('\n'));
}

main();
